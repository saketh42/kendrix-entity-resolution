-- 3) IRD donee list (optional source)
CREATE OR REPLACE TABLE RAW.IRD_DONEE (
    ORGANISATION_NAME VARCHAR, CEASED_AS_DONEE VARCHAR,
    _SOURCE_FILE VARCHAR, _LOADED_AT TIMESTAMP_NTZ
);

COPY INTO RAW.IRD_DONEE
FROM (
  SELECT $1,$2, METADATA$FILENAME, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
  FROM @RAW.LANDING/ird_donee.csv
)
FILE_FORMAT = (FORMAT_NAME = 'RAW.FF_CSV')
ON_ERROR = ABORT_STATEMENT;

-- 4) Audit log row (STATUS is FAIL if any count is wrong)
INSERT INTO AUDIT.PIPELINE_RUN (RUN_ID, STEP, STARTED_AT, FINISHED_AT, ROWS_OUT, RULE_VERSION, STATUS, NOTES)
SELECT UUID_STRING(), '02_raw',
       (SELECT MIN(_LOADED_AT) FROM RAW.CHARITIES_ORGANISATIONS),
       CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
       c.n, 'raw_v1',
       IFF(c.n = 46045 AND co.n = 2000 AND d.n = 39115, 'SUCCESS', 'FAIL'),
       'charities=' || c.n || ', companies_office=' || co.n || ', ird_donee=' || d.n
FROM (SELECT COUNT(*) n FROM RAW.CHARITIES_ORGANISATIONS) c,
     (SELECT COUNT(*) n FROM RAW.COMPANIES_OFFICE) co,
     (SELECT COUNT(*) n FROM RAW.IRD_DONEE) d;

-- 5) Row-count checks (last, so this result is what you see in Snowsight)
SELECT 'CHARITIES' AS source, COUNT(*) AS actual_rows, 46045 AS expected_rows,
       IFF(COUNT(*) = 46045, 'PASS', 'FAIL') AS check_result FROM RAW.CHARITIES_ORGANISATIONS
UNION ALL
SELECT 'COMPANIES_OFFICE', COUNT(*), 2000, IFF(COUNT(*) = 2000, 'PASS', 'FAIL') FROM RAW.COMPANIES_OFFICE
UNION ALL
SELECT 'IRD_DONEE', COUNT(*), 39115, IFF(COUNT(*) = 39115, 'PASS', 'FAIL') FROM RAW.IRD_DONEE;
