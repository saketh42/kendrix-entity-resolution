-- =============================================================================
-- 02_raw_tables.sql
-- Purpose : Create the RAW tables and load the three source files into them,
--           then check row counts and log the run.
-- Owner   : Data Engineer (Shubham)
-- Why all VARCHAR: RAW keeps data exactly as received, so nothing is lost or
--           mis-typed on load (e.g. leading zeros, odd date formats). Typing and
--           cleaning happen in STAGING.
-- Prerequisites:
--           1. sql/01_setup.sql has been run (RAW.FF_CSV, RAW.LANDING exist).
--           2. The 3 files from data/clean/ are uploaded to @RAW.LANDING:
--              charities_organisations.csv, companies_office.csv, ird_donee.csv
-- Inputs  : @RAW.LANDING/*.csv
-- Outputs : RAW.CHARITIES_ORGANISATIONS, RAW.COMPANIES_OFFICE, RAW.IRD_DONEE,
--           one row in AUDIT.PIPELINE_RUN (step '02_raw').
-- Notes   : Idempotent. CREATE OR REPLACE gives each table fresh COPY load
--           history, so a re-run reloads the files instead of skipping them.
-- =============================================================================
-- Note: the source CSV quotes every field, so blank values load as '' (empty string), not NULL. RAW keeps them as received; STAGING converts them with NULLIF(TRIM(col), '').

